package com.hospital.opd.model;

/** One row per finished consultation: analytics + ML training data. */
public class Consultation {
    public String consultationId;
    public String queueEntryId;
    public String doctorId;
    public String departmentId;
    public double durationMinutes;       // consultation length
    public double waitedMinutes;         // joinedAt -> consultationStartedAt  (ML target)
    public int patientsAheadAtJoin;
    public double avgDurationAtJoin;
    public int hour, dayOfWeek;
    public Source source;
    public long completedAt;
    public boolean simulated;            // true for demo data generated by the simulator
}
